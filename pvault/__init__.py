"""PassVault — офлайн-хранилище и генератор паролей.

Пакет намеренно разложен по слоям, и граница проведена в одном конкретном
месте: всё, кроме pvault/ui, не знает про tkinter и проверяется автотестами
без единого окна на экране.

Это не вкусовщина. В версии 1.x вся программа лежала одним файлом, и слой
записи на диск не проверялся ничем — именно там жил баг, стиравший хранилище
без возможности вернуть. Тест, который имитирует сбой ровно в опасный момент,
написать можно только к отделённому слою.

Слои:
    crypto      контейнер файла, получение ключа, шифрование
    model       записи, метки времени, история паролей, надгробия
    generator   генератор паролей
    merge       слияние двух хранилищ (оно же — восстановление из копии)
    paths       где лежат хранилище и служебные файлы к нему
    storage     атомарная запись, блокировка, поиск уцелевших копий
    backup      архив снимков и ротация
    portable    экспорт и импорт CSV/JSON
    throttle    задержка после неверных мастер-паролей
    config      настройки вне хранилища (какой файл открывали)
    netblock    отключение сетевых функций Python
    setup       установка и удаление программы
    ui          интерфейс
"""

